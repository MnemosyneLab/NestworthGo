const (
	cmdMove = iota
	cmdLine
	cmdCubic
	cmdClose
)

var (
	exportPattern = regexp.MustCompile(`export \{ default \} from '\./([a-z0-9-]+)\.mjs'`)
	elementStart  = regexp.MustCompile(`\[\s*"(path|circle|rect|line|polyline|polygon|ellipse)"\s*,\s*\{`)
	attribute     = regexp.MustCompile(`(\w+):\s*"([^"]*)"`)
)

func main() {
	src := flag.String("src", "../../frontend/node_modules/lucide-react/dist/esm/icons", "Lucide icon directory")
	out := flag.String("out", "internal/ui/lucide/icons_gen.go", "generated Go file")
	flag.Parse()

	names := make([]string, 0, len(icons))
	for name := range icons {
		names = append(names, name)
	}
	sort.Strings(names)

	var body bytes.Buffer
	for _, name := range names {
		paths, err := load(*src, name)
		if err != nil {
			fmt.Fprintln(os.Stderr, name+":", err)
			os.Exit(1)
		}
		fmt.Fprintf(&body, "// %s is the Lucide %q icon.\nvar %s = &Icon{paths: [][]float32{\n", icons[name], name, icons[name])
		for _, path := range paths {
			body.WriteString("{")
			for i, v := range path {
				if i > 0 {
					body.WriteString(", ")
				}
				body.WriteString(strconv.FormatFloat(float64(v), 'f', -1, 32))
			}
			body.WriteString("},\n")
		}
		body.WriteString("}}\n\n")
	}
	body.WriteString("// All lists every generated icon, for galleries and tests.\nfunc All() []*Icon {\n\treturn []*Icon{")
	for _, name := range names {
		body.WriteString(icons[name] + ", ")
	}
	body.WriteString("}\n}\n")
	header := "// Code generated by tools/lucidegen from lucide-react; DO NOT EDIT.\n\npackage lucide\n\n"
	formatted, err := format.Source([]byte(header + body.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// load follows Lucide alias modules until it finds the icon nodes.
func load(dir, name string) ([][]float32, error) {
	for range 4 {
		data, err := os.ReadFile(filepath.Join(dir, name+".mjs"))
		if err != nil {
			return nil, err
		}
		text := string(data)
		if m := exportPattern.FindStringSubmatch(text); m != nil {
			name = m[1]
			continue
		}
		start := strings.Index(text, "const __iconNode = [")
		end := strings.Index(text, "];\nconst ")
		if start < 0 || end < 0 {
			return nil, fmt.Errorf("no icon nodes in %s", name)
		}
		return nodes(text[start:end])
	}
	return nil, fmt.Errorf("alias chain too long")
}

func nodes(text string) ([][]float32, error) {
	var paths [][]float32
	for _, loc := range elementStart.FindAllStringSubmatchIndex(text, -1) {
		tag := text[loc[2]:loc[3]]
		rest := text[loc[1]:]
		if end := strings.Index(rest, "}"); end >= 0 {
			rest = rest[:end]
		}
		attrs := map[string]string{}
		for _, m := range attribute.FindAllStringSubmatch(rest, -1) {
			attrs[m[1]] = m[2]
		}
		path, err := shape(tag, attrs)
		if err != nil {
			return nil, err
		}
		paths = append(paths, path)
	}
	return paths, nil
}

func number(attrs map[string]string, key string) float64 {
	v, _ := strconv.ParseFloat(attrs[key], 64)
	return v
}

func shape(tag string, a map[string]string) ([]float32, error) {
	var b builder
	switch tag {
	case "path":
		return parsePath(a["d"])
	case "circle":
		b.ellipse(number(a, "cx"), number(a, "cy"), number(a, "r"), number(a, "r"))
	case "ellipse":
		b.ellipse(number(a, "cx"), number(a, "cy"), number(a, "rx"), number(a, "ry"))
	case "line":
		b.move(number(a, "x1"), number(a, "y1"))
		b.line(number(a, "x2"), number(a, "y2"))
	case "polyline", "polygon":
		values := numbers(a["points"])
		for i := 0; i+1 < len(values); i += 2 {
			if i == 0 {
				b.move(values[i], values[i+1])
			} else {
				b.line(values[i], values[i+1])
			}
		}
		if tag == "polygon" {
			b.close()
		}
	case "rect":
		x, y, w, h := number(a, "x"), number(a, "y"), number(a, "width"), number(a, "height")
		rx, ry := number(a, "rx"), number(a, "ry")
		if rx == 0 {
			rx = ry
		}
		if ry == 0 {
			ry = rx
		}
		rx, ry = math.Min(rx, w/2), math.Min(ry, h/2)
		b.move(x+rx, y)
		b.line(x+w-rx, y)
		b.arc(x+w-rx, y, rx, ry, 0, false, true, x+w, y+ry)
		b.line(x+w, y+h-ry)
		b.arc(x+w, y+h-ry, rx, ry, 0, false, true, x+w-rx, y+h)
		b.line(x+rx, y+h)
		b.arc(x+rx, y+h, rx, ry, 0, false, true, x, y+h-ry)
		b.line(x, y+ry)
		b.arc(x, y+ry, rx, ry, 0, false, true, x+rx, y)
		b.close()
	}
	return b.out, nil
}

func numbers(s string) []float64 {
	var out []float64
	for _, m := range regexp.MustCompile(`-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?`).FindAllString(s, -1) {
		v, _ := strconv.ParseFloat(m, 64)
		out = append(out, v)
	}
	return out
}

type builder struct {
	out                  []float32
	x, y, startX, startY float64
}

func (b *builder) emit(cmd int, v ...float64) {
	b.out = append(b.out, float32(cmd))
	for _, f := range v {
		b.out = append(b.out, float32(math.Round(f*1e4)/1e4))
	}
}

func (b *builder) move(x, y float64) {
	b.emit(cmdMove, x, y)
	b.x, b.y, b.startX, b.startY = x, y, x, y
}

func (b *builder) line(x, y float64) {
	b.emit(cmdLine, x, y)
	b.x, b.y = x, y
}

func (b *builder) cubic(x1, y1, x2, y2, x, y float64) {
	b.emit(cmdCubic, x1, y1, x2, y2, x, y)
	b.x, b.y = x, y
}

func (b *builder) close() {
	b.emit(cmdClose)
	b.x, b.y = b.startX, b.startY
}

func (b *builder) ellipse(cx, cy, rx, ry float64) {
	b.move(cx+rx, cy)
	b.arc(cx+rx, cy, rx, ry, 0, false, true, cx, cy+ry)
	b.arc(cx, cy+ry, rx, ry, 0, false, true, cx-rx, cy)
	b.arc(cx-rx, cy, rx, ry, 0, false, true, cx, cy-ry)
	b.arc(cx, cy-ry, rx, ry, 0, false, true, cx+rx, cy)
	b.close()
}

// arc appends an SVG elliptical arc from (x0,y0) as cubic Bezier segments,
// following the endpoint-to-centre conversion in the SVG implementation notes.
func (b *builder) arc(x0, y0, rx, ry, rotation float64, large, sweep bool, x, y float64) {
	if rx == 0 || ry == 0 || (x0 == x && y0 == y) {
		b.line(x, y)
		return
	}
	rx, ry = math.Abs(rx), math.Abs(ry)
	phi := rotation * math.Pi / 180
	cos, sin := math.Cos(phi), math.Sin(phi)
	dx, dy := (x0-x)/2, (y0-y)/2
	x1p, y1p := cos*dx+sin*dy, -sin*dx+cos*dy
	if lambda := x1p*x1p/(rx*rx) + y1p*y1p/(ry*ry); lambda > 1 {
		scale := math.Sqrt(lambda)
		rx, ry = rx*scale, ry*scale
	}
	numerator := rx*rx*ry*ry - rx*rx*y1p*y1p - ry*ry*x1p*x1p
	denominator := rx*rx*y1p*y1p + ry*ry*x1p*x1p
	coefficient := 0.0
	if denominator != 0 && numerator > 0 {
		coefficient = math.Sqrt(numerator / denominator)
	}
	if large == sweep {
		coefficient = -coefficient
	}
	cxp, cyp := coefficient*rx*y1p/ry, -coefficient*ry*x1p/rx
	cx, cy := cos*cxp-sin*cyp+(x0+x)/2, sin*cxp+cos*cyp+(y0+y)/2
	angle := func(ux, uy, vx, vy float64) float64 {
		dot := ux*vx + uy*vy
		length := math.Hypot(ux, uy) * math.Hypot(vx, vy)
		a := math.Acos(math.Max(-1, math.Min(1, dot/length)))
		if ux*vy-uy*vx < 0 {
			a = -a
		}
		return a
	}
	theta := angle(1, 0, (x1p-cxp)/rx, (y1p-cyp)/ry)
	delta := angle((x1p-cxp)/rx, (y1p-cyp)/ry, (-x1p-cxp)/rx, (-y1p-cyp)/ry)
	if !sweep && delta > 0 {
		delta -= 2 * math.Pi
	} else if sweep && delta < 0 {
		delta += 2 * math.Pi
	}
	segments := int(math.Ceil(math.Abs(delta) / (math.Pi / 2)))
	step := delta / float64(segments)
	k := 4.0 / 3.0 * math.Tan(step/4)
	point := func(t float64) (float64, float64, float64, float64) {
		ct, st := math.Cos(t), math.Sin(t)
		px, py := rx*ct, ry*st
		tx, ty := -rx*st, ry*ct
		return cos*px - sin*py + cx, sin*px + cos*py + cy, cos*tx - sin*ty, sin*tx + cos*ty
	}
	for i := 0; i < segments; i++ {
		a0, a1 := theta+float64(i)*step, theta+float64(i+1)*step
		px0, py0, tx0, ty0 := point(a0)
		px1, py1, tx1, ty1 := point(a1)
		b.cubic(px0+k*tx0, py0+k*ty0, px1-k*tx1, py1-k*ty1, px1, py1)
	}
	b.x, b.y = x, y
}

// parsePath converts SVG path data into absolute commands.
func parsePath(d string) ([]float32, error) {
	var b builder
	tokens := regexp.MustCompile(`[MmLlHhVvCcSsQqTtAaZz]|-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?`).FindAllString(d, -1)
	var cmd byte
	var lastCubicX, lastCubicY, lastQuadX, lastQuadY float64
	var prev byte
	next := func() float64 {
		v, _ := strconv.ParseFloat(tokens[0], 64)
		tokens = tokens[1:]
		return v
	}
	flag := func() bool {
		// Arc flags may be packed without separators, such as "a1 1 0 00.5.5".
		token := tokens[0]
		value := token[0] == '1'
		if len(token) > 1 {
			tokens[0] = token[1:]
		} else {
			tokens = tokens[1:]
		}
		return value
	}
	for len(tokens) > 0 {
		if t := tokens[0]; len(t) == 1 && strings.ContainsAny(t, "MmLlHhVvCcSsQqTtAaZz") {
			cmd = t[0]
			tokens = tokens[1:]
			if cmd == 'Z' || cmd == 'z' {
				b.close()
				prev = cmd
				continue
			}
		}
		rel := cmd >= 'a'
		ox, oy := 0.0, 0.0
		if rel {
			ox, oy = b.x, b.y
		}
		switch cmd | 0x20 {
		case 'm':
			b.move(next()+ox, next()+oy)
			cmd = 'L' | (cmd & 0x20)
		case 'l':
			b.line(next()+ox, next()+oy)
		case 'h':
			b.line(next()+ox, b.y)
		case 'v':
			b.line(b.x, next()+oy)
		case 'c':
			x1, y1, x2, y2, x, y := next()+ox, next()+oy, next()+ox, next()+oy, next()+ox, next()+oy
			b.cubic(x1, y1, x2, y2, x, y)
			lastCubicX, lastCubicY = x2, y2
		case 's':
			x1, y1 := b.x, b.y
			if prev|0x20 == 'c' || prev|0x20 == 's' {
				x1, y1 = 2*b.x-lastCubicX, 2*b.y-lastCubicY
			}
			x2, y2, x, y := next()+ox, next()+oy, next()+ox, next()+oy
			b.cubic(x1, y1, x2, y2, x, y)
			lastCubicX, lastCubicY = x2, y2
		case 'q', 't':
			x0, y0 := b.x, b.y
			var cx, cy float64
			if cmd|0x20 == 'q' {
				cx, cy = next()+ox, next()+oy
			} else {
				cx, cy = x0, y0
				if prev|0x20 == 'q' || prev|0x20 == 't' {
					cx, cy = 2*x0-lastQuadX, 2*y0-lastQuadY
				}
			}
			x, y := next()+ox, next()+oy
			b.cubic(x0+2.0/3*(cx-x0), y0+2.0/3*(cy-y0), x+2.0/3*(cx-x), y+2.0/3*(cy-y), x, y)
			lastQuadX, lastQuadY = cx, cy
		case 'a':
			rx, ry, rotation := next(), next(), next()
			large, sweep := flag(), flag()
			b.arc(b.x, b.y, rx, ry, rotation, large, sweep, next()+ox, next()+oy)
		default:
			return nil, fmt.Errorf("unsupported path command %q", cmd)
		}
		prev = cmd
	}
	return b.out, nil
}
