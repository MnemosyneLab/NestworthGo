// Command lucidegen converts Lucide icons into numeric path tables for the Gio
// UI. Lucide is the icon set the Wails frontend uses, so Gio and Wails share
// glyph shapes. Gio has no SVG renderer: the tool flattens every shape to
// absolute move, line, cubic and close commands that internal/ui/lucide draws
// as round-capped strokes.
//
// Usage, from experiments/gio:
//
//	go run ./tools/lucidegen -out internal/ui/lucide/icons_gen.go
